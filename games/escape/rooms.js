const box = (x0, y0, x1, y1) => [[x0, y0], [x1, y0], [x1, y1], [x0, y1]];

// 床・左右の壁・天井。gaps は床の穴（[x0, x1] の並び）。穴の底は y=-3 に張る
function frame(W, H, gaps = []) {
  const s = [box(-1, -4, 0, H + 1), box(W, -4, W + 1, H + 1), box(-1, H, W + 1, H + 1)];
  let x = -1;
  for (const [g0, g1] of [...gaps, [W + 1, W + 1]]) {
    if (g0 > x) s.push(box(x, -4, g0, 0));
    if (g1 > g0) s.push(box(g0, -4, g1, -3));
    x = g1;
  }
  return s;
}

// 板（スイッチ）：床の板は上面 y、天井の板は y=H。accept の字が乗ると光る
const floorPlate = (x0, x1, y, accept, reach = 0) => ({ x0, x1, y0: y, y1: y + 1.5, surf: y, accept, ceil: false, reach });
const ceilPlate = (x0, x1, H, accept) => ({ x0, x1, y0: H - 1.3, y1: H, surf: H, accept, ceil: true });

