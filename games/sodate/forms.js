// これ以上進化しない字（ここまで育つと旅立てる）
export const isFinal = ch => !EVO[ch];

// 次の字までに必要な成長ポイント（画数が多いほど多い）
export const needOf = ch => 24 + 6 * FORMS[ch].n;

// 分かれ道：その字の間にいちばん多くあげたエサの行き先。何もなし・同数なら表の先頭に近いほう
export function nextForm(ch, feeds) {
  const list = EVO[ch];
  if (!list) return null;
  let best = list[0], bestN = -1;
  for (const e of list) {
    const n = feeds[e.by] || 0;
    if (n > bestN) { best = e; bestN = n; }
  }
  return best.to;
}

// ツリーの親（もとの字）の一覧
export function parentsOf(ch) {
  return Object.entries(EVO).filter(([, l]) => l.some(e => e.to === ch)).map(([f]) => f);
}
