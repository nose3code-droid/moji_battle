// 半分 → 全体（中央の列は重ねない）
function mirror(half) {
  return half.map(r => r + [...r].slice(0, -1).reverse().join(''));
}

// 迷路を { rows, W, H } にして返す。stage は 0 始まり（5面を超えたら繰り返す）
export function getMaze(stage) {
  const rows = mirror(HALVES[stage % HALVES.length]);
  return { rows, W, H };
}
