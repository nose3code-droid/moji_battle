// 文字もぐらたたき：字ごとの属性データ
// 各字に持たせる属性（確信が持てないものは書かない＝未定義。未定義の字は「正解」にも「不正解」にも使わない）
//   s  : 画数（小学校で習う形での総画数）
//   r  : 部首のよび名（へん・かんむりなど、字の中で見える位置の部首）
//   on : 音読みの全部（常用漢字表にあるもの）。カタカナ
//   k  : 成り立ち（象形・指事・会意・形声）
//   c  : 成り立ちの組み立て（例：日＋月）
//   parts : 「日」が部品として入っているか（['日'] か []）
// 同じ字を別の行で重ねて書いてよい。食い違う値を書くと読み込み時に例外を出す（打ち間違いの検出）。
//
// 書き方：トークンは「字＋画数」（例：村7）。複数の行で同じ字が出てきたら、画数は一致していなければならない。

export const KANJI = {};

function put(ch, attrs) {
  if ([...ch].length !== 1) throw new Error(`1文字ではない: ${ch}`);
  const e = KANJI[ch] || (KANJI[ch] = {});
  for (const [key, v] of Object.entries(attrs)) {
    if (v == null) continue;
    if (e[key] !== undefined && JSON.stringify(e[key]) !== JSON.stringify(v)) {
      throw new Error(`属性が食い違う: ${ch}.${key} ${JSON.stringify(e[key])} と ${JSON.stringify(v)}`);
    }
    e[key] = v;
  }
}
const toks = str => str.trim().split(/\s+/);
const parse = t => {
  const m = t.match(/^(.)(\d*)(?::(.+))?$/u);
  if (!m) throw new Error(`書式エラー: ${t}`);
  return { ch: m[1], s: m[2] ? Number(m[2]) : undefined, rest: m[3] };
};

// 部首のよび名ごと。「字＋画数」
const rad = (name, str) => toks(str).forEach(t => { const { ch, s } = parse(t); put(ch, { r: name, s }); });
// 画数だけ
const strokes = str => toks(str).forEach(t => { const { ch, s } = parse(t); put(ch, { s }); });
// 「日」が入る字／入らない字（見た目が似ていても入らない字）
const nichi = (has, str) => toks(str).forEach(t => { const { ch, s } = parse(t); put(ch, { s, parts: has ? ['日'] : [] }); });
// 音読み「字＋画数:コウ・ク」
const on = str => toks(str).forEach(t => { const { ch, s, rest } = parse(t); put(ch, { s, on: rest.split('・') }); });
// 成り立ち「字＋画数:組み立て」
const kind = (k, str) => toks(str).forEach(t => { const { ch, s, rest } = parse(t); put(ch, { s, k, c: rest }); });

