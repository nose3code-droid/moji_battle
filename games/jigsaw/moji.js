const KANA_STROKES = { あ: 3, ハ: 2 };   // ひらがな・カタカナで画数が確実なもの

export const PRESETS = ['龍', '鬱', '森', '口', 'あ', 'S', '春', '愛', '一', 'ハ', '川'];
export const POOL = [...new Set([...Object.keys(MOJI), ...Object.keys(KANA_STROKES), 'S'])];

// 画数（わかるときだけ数。わからなければ null）
export function strokesOf(ch) {
  if (MOJI[ch]) return MOJI[ch][2];
  return KANA_STROKES[ch] ?? null;
}

// 完成したときのひとこと
export function hitokoto(ch) {
  const m = MOJI[ch];
  if (m) {
    const yomi = [m[0] && `音読み「${m[0]}」`, m[1] && `訓読み「${m[1]}」`].filter(Boolean).join('、');
    return `「${ch}」 ${yomi}、${m[2]}画の字。`;
  }
  if (/^[ぁ-ゖ]$/.test(ch)) return `「${ch}」は ひらがな${KANA_STROKES[ch] ? `、${KANA_STROKES[ch]}画` : ''}。`;
  if (/^[ァ-ヶ]$/.test(ch)) return `「${ch}」は カタカナ${KANA_STROKES[ch] ? `、${KANA_STROKES[ch]}画` : ''}。`;
  if (/^[A-Za-z]$/.test(ch)) return `「${ch}」は アルファベットの字。`;
  return `「${ch}」の完成！`;
}
